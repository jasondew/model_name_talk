defmodule Mix.Tasks.Talk.Outline do
  @shortdoc "Prints the running order, for reading and for editing against"

  @moduledoc """
  The talk as an outline, generated from `ModelNameTalk.Deck`.

  A hand written outline drifts from the deck the first time a slide moves.
  This one cannot: it is the deck, printed. Read it to decide what the talk
  says, then change `lib/model_name_talk/deck.ex`, which is the only place
  the running order lives.

      mix talk.outline             the whole talk
      mix talk.outline --notes     with every speaker note
      mix talk.outline 7           one chapter
      mix talk.outline --markdown  write docs/outline.md, to edit and hand back

  A slide marked `[stub]` has no drawing of its own yet and renders as its
  title alone under the file name, with its notes on the presenter view only.
  """

  use Mix.Task

  import Phoenix.LiveViewTest, only: [render_component: 2]

  alias ModelNameTalk.{Deck, Round, Slide}

  @impl Mix.Task
  def run(arguments) do
    Mix.Task.run("app.start")

    {options, chapters, _invalid} =
      OptionParser.parse(arguments, switches: [notes: :boolean, markdown: :boolean])

    wanted = Enum.map(chapters, &String.to_integer/1)

    sections = Enum.filter(Deck.sections(), &(wanted == [] or &1.number in wanted))

    if Keyword.get(options, :markdown, false) do
      write_markdown(sections)
    else
      Enum.each(sections, &print_section(&1, options))
      print_summary()
    end
  end

  ## PRIVATE FUNCTIONS

  @markdown_path "docs/outline.md"

  defp write_markdown(sections) do
    File.write!(@markdown_path, markdown(sections))

    Mix.shell().info("Wrote #{@markdown_path}. Edit it and hand it back.")
  end

  defp markdown(sections) do
    [preamble(), Enum.map(sections, &markdown_section/1)]
    |> IO.iodata_to_binary()
  end

  defp preamble do
    slides = Deck.slides()
    minutes = Deck.sections() |> Enum.map(& &1.minutes) |> Enum.sum()

    """
    # What's in a name?

    #{minutes} minutes, #{length(slides)} slides, #{Enum.count(slides, & &1.round)} rounds, #{slides |> Enum.flat_map(&Slide.definitions/1) |> length()} terms.

    Generated by `mix talk.outline --markdown` from `lib/model_name_talk/deck.ex`,
    which is where the running order actually lives. Edit this file and hand it
    back, and the changes get applied there.

    ## How to edit it

    The `id` on each slide is the key. Keep it and the edit lands on that slide;
    change the heading text beside it and you have retitled the slide. To add a
    slide, write a new heading with an id nobody else is using. To cut one,
    delete its block. To move one, move its block.

    Note lines carry their meaning in the first character, and they are what the
    speaker reads, never what the slide should look like:

    - a cue, a short phrase
    ! a point that has to be made out loud, drawn lit on the speaker's screen
    = term: a definition, which is also the term card and the audience handout

    `[stub]` means the content is written but nobody has drawn the slide yet, so
    it renders hatched with its title and notes showing. That is not a fault to
    fix here; it is a drawing job.

    `minutes` includes the round that closes the chapter. `lands` is the one
    thing the chapter has to leave behind, and the speaker sees it all chapter.

    ---
    """
  end

  defp markdown_section(section) do
    """

    ## #{section.number}. #{section.title}

    - **minutes:** #{section.minutes}
    - **lands:** #{section.lands}

    #{Enum.map_join(section.slides, "", &markdown_slide(&1, section.number))}
    """
  end

  defp markdown_slide(slide, number) do
    slide = %{slide | section: number}

    """
    ### `#{slide.id}` #{slide.title}
    #{markdown_marks(slide)}
    ```
    #{String.trim_trailing(notes_source(slide))}
    ```

    """
  end

  defp markdown_marks(slide) do
    marks =
      [
        if(slide.steps > 1, do: "#{slide.steps} steps"),
        if(slide.round, do: "round `#{slide.round}`"),
        if(stub?(slide), do: "[stub]")
      ]
      |> Enum.reject(&is_nil/1)

    case marks do
      [] -> ""
      marks -> "\n*#{Enum.join(marks, ", ")}*\n"
    end
  end

  # The notes as written, so an edit can be pasted straight back into the deck.
  defp notes_source(%Slide{notes: notes}) do
    notes |> String.split("\n") |> Enum.map_join("\n", &String.trim_trailing/1)
  end

  defp stub?(slide) do
    render_component(&ModelNameTalkWeb.SlideComponents.slide/1,
      slide: slide,
      step: 1
    )
    |> String.contains?("slide--undrawn")
  rescue
    _error -> false
  end

  defp print_section(section, options) do
    Mix.shell().info("")

    Mix.shell().info(
      IO.ANSI.bright() <>
        "#{section.number}. #{section.title}" <>
        IO.ANSI.reset() <>
        IO.ANSI.faint() <>
        "  #{section.minutes} min, #{length(section.slides)} slides" <> IO.ANSI.reset()
    )

    Mix.shell().info(IO.ANSI.faint() <> "   lands: #{section.lands}" <> IO.ANSI.reset())
    Mix.shell().info("")

    section.slides
    |> Enum.map(&%{&1 | section: section.number})
    |> Enum.each(&print_slide(&1, options))
  end

  defp print_slide(slide, options) do
    Mix.shell().info("   " <> title_line(slide))

    if Keyword.get(options, :notes, false) do
      slide |> Slide.blocks() |> Enum.each(&print_block/1)
      Mix.shell().info("")
    end
  end

  defp title_line(slide) do
    [
      IO.ANSI.faint(),
      String.pad_trailing(to_string(slide.id), 28),
      IO.ANSI.reset(),
      slide.title,
      marks(slide)
    ]
    |> Enum.join()
  end

  defp marks(slide) do
    [steps_mark(slide), round_mark(slide), stub_mark(slide)]
    |> Enum.reject(&(&1 == ""))
    |> Enum.join()
  end

  defp steps_mark(%Slide{steps: 1}), do: ""

  defp steps_mark(%Slide{steps: steps}),
    do: IO.ANSI.faint() <> "  #{steps} steps" <> IO.ANSI.reset()

  defp round_mark(%Slide{round: nil}), do: ""

  defp round_mark(%Slide{round: identifier}) do
    round = Round.fetch(identifier)

    IO.ANSI.yellow() <>
      "  ROUND #{round.seconds}s #{round.type}" <> IO.ANSI.reset()
  end

  # Rendering is the only honest way to ask whether a slide has a drawing of
  # its own: the clause it would match lives in the component, not the data.
  defp stub_mark(slide) do
    if stub?(slide), do: IO.ANSI.faint() <> "  [stub]" <> IO.ANSI.reset(), else: ""
  end

  defp print_block({:cues, cues}) do
    Enum.each(cues, &Mix.shell().info(IO.ANSI.faint() <> "       - #{&1}" <> IO.ANSI.reset()))
  end

  defp print_block({:musts, musts}) do
    Enum.each(musts, &Mix.shell().info("       ! #{&1}"))
  end

  defp print_block({:definitions, pairs}) do
    Enum.each(pairs, fn {term, meaning} ->
      Mix.shell().info(
        IO.ANSI.yellow() <>
          "       #{term}: " <>
          IO.ANSI.reset() <>
          IO.ANSI.faint() <>
          meaning <> IO.ANSI.reset()
      )
    end)
  end

  defp print_summary do
    slides = Deck.slides()
    minutes = Deck.sections() |> Enum.map(& &1.minutes) |> Enum.sum()
    presses = slides |> Enum.map(& &1.steps) |> Enum.sum()
    rounds = Enum.count(slides, & &1.round)
    terms = slides |> Enum.flat_map(&Slide.definitions/1) |> length()

    Mix.shell().info("")

    Mix.shell().info(
      IO.ANSI.bright() <>
        "#{minutes} minutes, #{length(slides)} slides, #{presses} presses, " <>
        "#{rounds} rounds, #{terms} terms" <> IO.ANSI.reset()
    )

    Mix.shell().info("")
  end
end
